  static List<FoodModel> getByCategory(String category) {
    if (category == 'All') return allFoods;
    return allFoods
        .where((f) => f.category.toLowerCase() == category.toLowerCase())
        .toList();
  }

  static List<FoodModel> search(String query) {
    if (query.trim().isEmpty) return allFoods;
    final q = query.toLowerCase().trim();
    return allFoods.where((f) {
      return f.name.toLowerCase().contains(q) ||
          f.category.toLowerCase().contains(q) ||
          f.description.toLowerCase().contains(q) ||
          f.healthBenefits.any((b) => b.toLowerCase().contains(q));
    }).toList();
  }

  static FoodModel findByName(String query) {
    final q = query.toLowerCase().trim();
    return allFoods.firstWhere(
      (f) => f.name.toLowerCase() == q || f.name.toLowerCase().contains(q),
      orElse: () {
        final match = allFoods.where((f) => f.name.toLowerCase().contains(q) || f.category.toLowerCase().contains(q)).toList();
        if (match.isNotEmpty) return match.first;
        return allFoods[0];
      },
    );
  }
